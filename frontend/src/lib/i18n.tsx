const DICTS: Record<Lang, Dict> = { en, hi };

export type Mode = "simple" | "expert";
type Ctx = { lang: Lang; t: Dict; setLang: (l: Lang) => void; large: boolean; setLarge: (b: boolean) => void; mode: Mode; setMode: (m: Mode) => void };
const LangCtx = createContext<Ctx | null>(null);

const PREF_EVT = "pardarshi:prefs";
function readPref(key: string): string | null {
  try {
    return localStorage.getItem(key);
  } catch {
    return null;
  }
}
function writePref(key: string, value: string) {
  try {
    localStorage.setItem(key, value);
  } catch {
    /* storage blocked: preference lasts for this page only */
  }
  window.dispatchEvent(new Event(PREF_EVT));
}
function subscribePrefs(cb: () => void) {
  window.addEventListener(PREF_EVT, cb);
  window.addEventListener("storage", cb);
  return () => {
    window.removeEventListener(PREF_EVT, cb);
    window.removeEventListener("storage", cb);
  };
}

export function LangProvider({ children }: { children: React.ReactNode }) {
  const lang: Lang = useSyncExternalStore(subscribePrefs, () => (readPref("pardarshi:lang") === "hi" ? "hi" : "en"), () => "en");
  const large = useSyncExternalStore(subscribePrefs, () => readPref("pardarshi:large") === "1", () => false);
  const mode: Mode = useSyncExternalStore(subscribePrefs, () => (readPref("pardarshi:mode") === "expert" ? "expert" : "simple"), () => "simple");

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dataset.text = large ? "large" : "normal";
  }, [lang, large]);

  const setLang = useCallback((l: Lang) => writePref("pardarshi:lang", l), []);
  const setLarge = useCallback((b: boolean) => writePref("pardarshi:large", b ? "1" : "0"), []);
  const setMode = useCallback((m: Mode) => writePref("pardarshi:mode", m), []);

  const value = useMemo(() => ({ lang, t: DICTS[lang], setLang, large, setLarge, mode, setMode }), [lang, setLang, large, setLarge, mode, setMode]);
  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}

export function useLang(): Ctx {
  const c = useContext(LangCtx);
  if (!c) throw new Error("useLang outside LangProvider");
  return c;
}

export const fill = (s: string, vars: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
